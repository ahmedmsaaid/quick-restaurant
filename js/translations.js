// Retrieve active language preference
export function getLanguage() {
    return localStorage.getItem('qs_lang') || 'en';
}

// Change active language preference & update page layouts
export function setLanguage(lang) {
    localStorage.setItem('qs_lang', lang);
    applyLanguageLayout(lang);
    notifySubscribers(lang);
}

// Translate a given key to the active language
export function t(key, replacements = {}) {
    const lang = getLanguage();
    let text = translations[lang][key] || translations['en'][key] || key;
    
    // Process string replacements
    Object.entries(replacements).forEach(([k, val]) => {
        text = text.replace(new RegExp(`{${k}}`, 'g'), val);
    });
    
    return text;
}

// Apply RTL directionality and language codes to HTML tag
export function applyLanguageLayout(lang) {
    const html = document.documentElement;
    if (html) {
        html.setAttribute('lang', lang);
        if (lang === 'ar') {
            html.setAttribute('dir', 'rtl');
        } else {
            html.setAttribute('dir', 'ltr');
        }
    }
}

// Translate all DOM elements tagged with data-i18n attributes on a page
export function initTranslations() {
    const activeLang = getLanguage();
    applyLanguageLayout(activeLang);

    // Apply translations on elements with data-i18n
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        el.textContent = t(key);
    });

    // Translate placeholder attributes on elements with data-i18n-placeholder
    const inputElements = document.querySelectorAll('[data-i18n-placeholder]');
    inputElements.forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        el.setAttribute('placeholder', t(key));
    });
}

// Initialize on DOM load
document.addEventListener('DOMContentLoaded', () => {
    initTranslations();
});
